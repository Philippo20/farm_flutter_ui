  // ========== HELPER METHOD ==========
  
  /// Get sensor icon by type
  static IconData getSensorIcon(String sensorType, {bool filled = false}) {
    switch (sensorType.toLowerCase()) {
      case 'temperature':
        return filled ? temperatureFilled : temperature;
      case 'humidity':
        return filled ? humidityFilled : humidity;
      case 'co2':
        return filled ? co2Filled : co2;
      case 'light':
        return filled ? lightFilled : light;
      case 'ph':
        return filled ? phFilled : ph;
      case 'ec':
        return filled ? ecFilled : ec;
      case 'electricity':
      case 'current':
      case 'voltage':
      case 'wattage':
        return filled ? electricityFilled : electricity;
      default:
        return Icons.sensors_outlined;
    }
  }
  
  /// Get status icon by status
  static IconData getStatusIcon(String status, {bool filled = false}) {
    switch (status.toLowerCase()) {
      case 'active':
      case 'online':
      case 'good':
        return filled ? statusActiveFilled : statusActive;
      case 'inactive':
      case 'offline':
        return filled ? statusInactiveFilled : statusInactive;
      case 'warning':
        return filled ? statusWarningFilled : statusWarning;
      case 'error':
      case 'danger':
      case 'critical':
        return filled ? statusErrorFilled : statusError;
      default:
        return Icons.help_outline;
    }
  }
  
  /// Get role icon by role
  static IconData getRoleIcon(String role, {bool filled = false}) {
    switch (role.toLowerCase()) {
      case 'admin':
        return filled ? adminFilled : admin;
      case 'owner':
        return filled ? ownerFilled : owner;
      case 'caretaker':
        return filled ? caretakerFilled : caretaker;
      default:
        return filled ? userFilled : user;
    }
  }
